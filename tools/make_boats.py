"""Sea routes of this world, read from the captains' own scripts.

A passage is what a player buys: stand by the captain, say hi, the destination, yes. The datapack
keeps these in addTravelKeyword calls; the captain's place comes from the NPC spawn file.
Usage: python -I tools/make_boats.py <datapack dir> packages/contracts/boats.json
"""
import glob
import json
import os
import re
import sys

# A fifth argument is a condition, usually a quest: such a passage is not for everyone, so it is left out.
TRAVEL = re.compile(r'addTravelKeyword\("([^"]+)",\s*(\d+),\s*Position\((\d+),\s*(\d+),\s*(\d+)\)(?!,\s*nil,\s*function)')
NAME = re.compile(r'local internalNpcName = "([^"]+)"')


def places(path):
    """NPC name -> spawn tiles, an NPC can stand in several towns."""
    found = {}
    text = open(path, encoding='utf-8', errors='ignore').read()
    for m in re.finditer(r'<npc centerx="(\d+)" centery="(\d+)" centerz="(\d+)"[^>]*>\s*<npc name="([^"]+)" x="(-?\d+)" y="(-?\d+)"', text):
        cx, cy, z, name, dx, dy = m.groups()
        found.setdefault(name, []).append({'x': int(cx) + int(dx), 'y': int(cy) + int(dy), 'z': int(z)})
    return found


def main(datapack, out_path):
    spawned = places(os.path.join(datapack, 'world', 'otservbr-npc.xml'))
    boats = []
    for path in sorted(glob.glob(os.path.join(datapack, 'npc', '*.lua'))):
        text = open(path, encoding='utf-8', errors='ignore').read()
        name = NAME.search(text)
        stops = [{'word': w, 'price': int(p), 'to': {'x': int(x), 'y': int(y), 'z': int(z)}} for w, p, x, y, z in TRAVEL.findall(text)]
        if not name or not stops or name.group(1) not in spawned:
            continue
        for at in spawned[name.group(1)]:
            boats.append({'npc': name.group(1), **at, 'stops': stops})
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'Generated by tools/make_boats.py from the datapack.', 'boats': boats}, f, ensure_ascii=False, indent=1)
    print({'captains': len(boats), 'stops': sum(len(b['stops']) for b in boats)})


if __name__ == '__main__':
    main(*sys.argv[1:3])
