"""Hunting grounds for player agents, from the monsters this world really spawns.

Groups a datapack's spawn file into places a player would name, with how hard they are, and leaves
out the beginners' islands: this world starts on the main land.
Usage: python -I tools/make_grounds.py <monster.xml> atlas.json game-data.json out.json
"""
import json
import re
import sys

CELL = 48
MIN_MONSTERS = 4
SKIPPED_TOWNS = {'Rookgaard', 'Dawnport', 'Dawnport Tutorial', 'Island of Destiny'}
TIER_EXPERIENCE = (40, 200, 700, 2500)
WORDS = {(0, -1): 'na polnoc', (0, 1): 'na poludnie', (1, 0): 'na wschod', (-1, 0): 'na zachod'}
SEA_LEVEL = 7
SHOWN_MONSTERS = 4


def tier_of(names, monsters):
    known = [monsters[n]['experience'] for n in names if n in monsters]
    typical = sorted(known)[len(known) // 2] if known else 0
    return sum(typical >= limit for limit in TIER_EXPERIENCE)


def describe(at, towns):
    town = min(towns, key=lambda t: max(abs(at[0] - t['temple']['x']), abs(at[1] - t['temple']['y'])))
    dx, dy = at[0] - town['temple']['x'], at[1] - town['temple']['y']
    way = WORDS[(0, 1 if dy > 0 else -1)] if abs(dy) >= abs(dx) else WORDS[(1 if dx > 0 else -1, 0)]
    floors = at[2] - SEA_LEVEL
    depth = 'na powierzchni' if floors == 0 else f'{floors} pod ziemia' if floors > 0 else f'{-floors} pietro w gore'
    return town['name'], f'{way} od {town["name"]}, {depth}'


def main(spawn_path, atlas_path, game_data_path, out_path):
    towns = json.load(open(atlas_path, encoding='utf-8'))['towns']
    monsters = json.load(open(game_data_path, encoding='utf-8'))['monsters']
    cells = {}
    text = open(spawn_path, encoding='utf-8', errors='ignore').read()
    for m in re.finditer(r'<monster centerx="(\d+)" centery="(\d+)" centerz="(\d+)"[^>]*>(.*?)</monster>', text, re.S):
        x, y, z = int(m.group(1)), int(m.group(2)), int(m.group(3))
        names = re.findall(r'name="([^"]+)"', m.group(4))
        if not names:
            continue
        cell = cells.setdefault((x // CELL, y // CELL, z), {'names': [], 'at': (x, y, z)})
        cell['names'].extend(names)
    grounds = []
    for c in cells.values():
        if len(c['names']) < MIN_MONSTERS:
            continue
        town, name = describe(c['at'], towns)
        if town in SKIPPED_TOWNS:
            continue
        counted = sorted(set(c['names']), key=lambda n: -c['names'].count(n))
        x, y, z = c['at']
        grounds.append({'name': name, 'town': town, 'tier': tier_of(c['names'], monsters), 'monsters': counted[:SHOWN_MONSTERS], 'count': len(c['names']), 'x': x, 'y': y, 'z': z})
    grounds.sort(key=lambda g: -g['count'])
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'Generated by tools/make_grounds.py from the datapack spawns.', 'grounds': grounds}, f, ensure_ascii=False, indent=0)
    print({'cells': len(cells), 'grounds': len(grounds), 'perTier': [sum(g['tier'] == t for g in grounds) for t in range(5)]})


if __name__ == '__main__':
    main(*sys.argv[1:5])
