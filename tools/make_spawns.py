"""Generates the world's monster spawns from the engine survey and the bestiary.

Danger grows with distance from a town and with depth, so a new character can survive near a town
and a strong one has a reason to go far and low. Deterministic for a given seed. The town centres
stay free: Montag has to remain a safe place for the agents and for tests.
Usage: python -I tools/make_spawns.py <survey.jsonl> [more.jsonl ...] --towns atlas.json --out canary-monster.xml
"""
import argparse
import json
import random

TIERS = [
    ['Cave Rat', 'Snake', 'Spider', 'Wolf', 'Bat', 'Sandcrawler'],
    ['Troll', 'Goblin', 'Skeleton', 'Wasp', 'Poison Spider', 'Frost Troll', 'Salamander'],
    ['Crocodile', 'Amazon', 'Toad', 'Bandit', 'Ghoul', 'Valkyrie', 'Tortoise'],
    ['Assassin', 'Cyclops', 'Hunter', 'Mummy', 'Slime', 'Monk', 'Cyclops Drone'],
    ['Cyclops Smith', 'Hydra'],
]
TOWN_RADIUS = 40
SPAWN_TIME = 120
SEA_LEVEL = 7
GROUND_CELL = 48
SERVICE_ROOM = 'Tps Room'
SERVICE_RADIUS = 1500


def tier_of(distance, z):
    """Depth counts like distance: one floor down is about as dangerous as 60 tiles away."""
    depth = max(0, z - SEA_LEVEL)
    danger = distance + depth * 60
    for tier, limit in enumerate((110, 200, 320, 480)):
        if danger < limit:
            return tier
    return len(TIERS) - 1


WORDS = {(0, -1): 'na polnoc', (0, 1): 'na poludnie', (1, 0): 'na wschod', (-1, 0): 'na zachod'}


def write_grounds(placed, towns, path):
    """Groups spawns into places a player would name: what lives there and how to find it."""
    cells = {}
    for p in placed:
        cell = (p['x'] // GROUND_CELL, p['y'] // GROUND_CELL, p['z'])
        c = cells.setdefault(cell, {'monsters': {}, 'tier': 0, 'at': None, 'count': 0})
        c['monsters'][p['name']] = c['monsters'].get(p['name'], 0) + p['count']
        c['tier'] = max(c['tier'], p['tier'])
        c['count'] += p['count']
        c['at'] = c['at'] or {'x': p['at'][0], 'y': p['at'][1], 'z': p['z']}
    land = [t for t in towns if t['name'] != SERVICE_ROOM]
    grounds = []
    for c in sorted(cells.values(), key=lambda c: -c['count']):
        if c['count'] < 3:
            continue
        at = c['at']
        town = min(land, key=lambda t: max(abs(at['x'] - t['temple']['x']), abs(at['y'] - t['temple']['y'])))
        dx, dy = at['x'] - town['temple']['x'], at['y'] - town['temple']['y']
        way = WORDS[(0, 1 if dy > 0 else -1)] if abs(dy) >= abs(dx) else WORDS[(1 if dx > 0 else -1, 0)]
        floors = at['z'] - 7
        depth = 'na powierzchni' if floors == 0 else f'{floors} pod ziemia' if floors > 0 else f'{-floors} pietro w gore'
        grounds.append({'name': f'{way} od {town["name"]}, {depth}', 'town': town['name'], 'tier': c['tier'], 'monsters': sorted(c['monsters']), **at})
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'Generated by tools/make_spawns.py. What a player of this world knows about where to hunt.', 'grounds': grounds}, f, ensure_ascii=False, indent=0)
    print({'grounds': len(grounds)})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('surveys', nargs='+')
    ap.add_argument('--towns', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--seed', type=int, default=7)
    ap.add_argument('--density', type=float, default=0.22)
    ap.add_argument('--grounds', help='hunting grounds summary for agents')
    args = ap.parse_args()
    rng = random.Random(args.seed)
    all_towns = json.load(open(args.towns))['towns']
    towns = [t['temple'] for t in all_towns if t['name'] != SERVICE_ROOM]
    room = next((t['temple'] for t in all_towns if t['name'] == SERVICE_ROOM), None)
    chunks = []
    for path in args.surveys:
        for line in open(path, encoding='utf-8'):
            if line.strip():
                chunks.append(json.loads(line))
    groups = []
    per_tier = [0] * len(TIERS)
    placed = []
    for c in sorted(chunks, key=lambda c: (c['z'], c['x'], c['y'])):
        cx, cy = c['x'] + 8, c['y'] + 8
        if room and max(abs(cx - room['x']), abs(cy - room['y'])) < SERVICE_RADIUS:
            continue
        distance = min(max(abs(cx - t['x']), abs(cy - t['y'])) for t in towns)
        if distance < TOWN_RADIUS and c['z'] <= SEA_LEVEL:
            continue
        if len(c['free']) < 2 or rng.random() > args.density:
            continue
        tier = tier_of(distance, c['z'])
        name = rng.choice(TIERS[tier])
        spots = rng.sample(c['free'], min(len(c['free']), rng.randint(1, 3)))
        rows = []
        for x, y in spots:
            rows.append(f'\t\t<monster name="{name}" x="{x - cx}" y="{y - cy}" z="0" spawntime="{SPAWN_TIME}" />')
        radius = max(max(abs(x - cx), abs(y - cy)) for x, y in spots) + 1
        groups.append(f'\t<monster centerx="{cx}" centery="{cy}" centerz="{c["z"]}" radius="{radius}">\n' + '\n'.join(rows) + '\n\t</monster>')
        per_tier[tier] += len(spots)
        placed.append({'x': cx, 'y': cy, 'z': c['z'], 'name': name, 'count': len(spots), 'tier': tier, 'at': spots[0]})
    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('<?xml version="1.0"?>\n<monsters>\n' + '\n'.join(groups) + '\n</monsters>\n')
    print({'chunks': len(chunks), 'groups': len(groups), 'perTier': per_tier})
    if args.grounds:
        write_grounds(placed, json.load(open(args.towns))['towns'], args.grounds)


if __name__ == '__main__':
    main()
