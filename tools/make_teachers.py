"""Spell teachers of this world, read from the NPC scripts.

A spell is learned like a player does it: stand by the teacher, say hi, the spell's name, yes. The
server takes the money and teaches. The teacher's place comes from the NPC spawn file.
Usage: python -I tools/make_teachers.py <datapack dir> packages/contracts/teachers.json
"""
import glob
import json
import os
import re
import sys

from make_boats import NAME, places

VOCATIONS = {1: 'sorcerer', 2: 'druid', 3: 'paladin', 4: 'knight', 5: 'sorcerer', 6: 'druid', 7: 'paladin', 8: 'knight'}
PLAIN = re.compile(r'addKeyword\(\{\s*"([^"]+)"\s*\}[^\n]*\n[^\n]*StdModule\.learnSpell,\s*\{([^\n]*)\}\)')
KEYWORD = re.compile(r'addSpellKeyword\(\{([^}]*)\},\s*\{(.*?)\}\)', re.S)


def field(text, name):
    m = re.search(name + r'\s*=\s*("([^"]*)"|\{([^}]*)\}|[\w.]+)', text)
    if not m:
        return None
    return m.group(2) if m.group(2) is not None else (m.group(3) if m.group(3) is not None else m.group(1))


def lesson(word, body):
    spell = field(body, 'spellName')
    price = field(body, 'price')
    if not spell or price is None or not price.isdigit():
        return None
    ids = [int(v) for v in re.findall(r'\d+', field(body, 'vocation') or '')]
    return {
        'spell': spell, 'word': word, 'price': int(price), 'level': int(field(body, 'level') or 1),
        'vocations': sorted({VOCATIONS[i] for i in ids if i in VOCATIONS}), 'premium': field(body, 'premium') == 'true',
    }


def main(datapack, out_path):
    spawned = places(os.path.join(datapack, 'world', 'otservbr-npc.xml'))
    teachers = []
    for path in sorted(glob.glob(os.path.join(datapack, 'npc', '*.lua'))):
        text = open(path, encoding='utf-8', errors='ignore').read()
        name = NAME.search(text)
        if not name or name.group(1) not in spawned:
            continue
        found = [lesson(word, body) for word, body in PLAIN.findall(text)]
        found += [lesson(' '.join(re.findall(r'"([^"]+)"', keys)), body) for keys, body in KEYWORD.findall(text)]
        spells = [s for s in found if s]
        if not spells:
            continue
        for at in spawned[name.group(1)]:
            teachers.append({'npc': name.group(1), **at, 'spells': spells})
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'Generated by tools/make_teachers.py from the datapack.', 'teachers': teachers}, f, ensure_ascii=False, indent=1)
    print({'teachers': len(teachers), 'lessons': sum(len(t['spells']) for t in teachers)})


if __name__ == '__main__':
    main(*sys.argv[1:3])
