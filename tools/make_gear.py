"""Armour worth saving for: what a gear merchant of the datapack really sells, at his prices.

Prices and stock come from the NPC's own shop list, protection from items.xml. Only what can be worn
on the armour slots: weapons follow skills, which a character builds over time, so it keeps its own.
Usage: python -I tools/make_gear.py <canary dir> packages/contracts/gear-shops.json
"""
import json
import os
import re
import sys

DATAPACK = 'data-otservbr-global'
MERCHANTS = ['Sam']
SLOTS = {'head': 1, 'armor': 4, 'legs': 7, 'feet': 8}
SHIELD_SLOT = 5


def item_table(path):
    """id -> {name, slot, value, level}: value is armour, or defense for a shield."""
    text = open(path, encoding='utf-8', errors='ignore').read()
    items = {}
    for m in re.finditer(r'<item\s+id="(\d+)"[^>]*?name="([^"]+)"[^>]*?>(.*?)</item>', text, re.S):
        item_id, name, body = int(m.group(1)), m.group(2).lower(), m.group(3)
        stats = dict(re.findall(r'key="(\w+)"\s+value="([^"]+)"', body))
        slot = SHIELD_SLOT if stats.get('weaponType') == 'shield' else SLOTS.get(stats.get('slot', ''))
        value = int(stats.get('defense', 0)) if slot == SHIELD_SLOT else int(stats.get('armor', 0))
        if slot and value > 0 and 'vocation' not in stats:
            items[item_id] = {'name': name, 'slot': slot, 'value': value, 'level': int(stats.get('minimumLevel', stats.get('level', 0))), 'weight': int(stats.get('weight', 0)) // 100}
    return items


def merchant_at(world_npc_xml, name):
    text = open(world_npc_xml, encoding='utf-8', errors='ignore').read()
    m = re.search(r'<npc centerx="(\d+)" centery="(\d+)" centerz="(\d+)"[^>]*>\s*<npc name="%s" x="(-?\d+)" y="(-?\d+)"' % name, text)
    return {'x': int(m.group(1)) + int(m.group(4)), 'y': int(m.group(2)) + int(m.group(5)), 'z': int(m.group(3))}


def stock(npc_lua):
    text = open(npc_lua, encoding='utf-8', errors='ignore').read()
    return {int(i): int(p) for i, p in re.findall(r'clientId = (\d+), buy = (\d+)', text)}


def main(canary, out):
    items = item_table(os.path.join(canary, 'data', 'items', 'items.xml'))
    shops = []
    for name in MERCHANTS:
        prices = stock(os.path.join(canary, DATAPACK, 'npc', f'{name.lower()}.lua'))
        goods = [{'id': i, 'price': p, **items[i]} for i, p in sorted(prices.items()) if i in items]
        shops.append({'npc': name, **merchant_at(os.path.join(canary, DATAPACK, 'world', 'otservbr-npc.xml'), name), 'items': goods})
    values = {str(i): {'slot': v['slot'], 'value': v['value']} for i, v in items.items()}
    potion_shops = []
    npc_dir = os.path.join(canary, DATAPACK, 'npc')
    for file in sorted(os.listdir(npc_dir)):
        path = os.path.join(npc_dir, file)
        text = open(path, encoding='utf-8', errors='ignore').read() if file.endswith('.lua') else ''
        if not re.search(r'itemName = "health potion", clientId = \d+, buy = \d+', text):
            continue
        name = re.search(r'internalNpcName = "([^"]+)"', text)
        try:
            potion_shops.append({'name': name.group(1), **merchant_at(os.path.join(canary, DATAPACK, 'world', 'otservbr-npc.xml'), name.group(1))})
        except AttributeError:
            continue  # sold only somewhere this map does not place
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'schemaVersion': 1, '_comment': 'Generated by tools/make_gear.py from the datapack. Do not edit by hand.', 'shops': shops, 'potionShops': potion_shops, 'values': values}, f, indent=0, sort_keys=True)
        f.write('\n')
    for shop in shops:
        print(shop['npc'], shop['x'], shop['y'], shop['z'], len(shop['items']))
        for g in sorted(shop['items'], key=lambda g: (g['slot'], g['value'])):
            print(' ', g['slot'], g['name'], g['value'], g['price'], g['level'])


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
