"""Builds the merchant's price list: what she sells, and what she buys back from the world's loot.

Sold goods are chosen by hand. Bought goods come from the loot of monsters that really spawn, and
the price follows the item's stats, so new spawns bring new trade without manual work.
Usage: python -I tools/make_shop.py <canary dir> <canary-monster.xml> packages/contracts/shop.json
"""
import glob
import json
import os
import re
import sys

SOLD = [
    ('health potion', 266, 15), ('mana potion', 268, 15), ('arrow', 3447, 1), ('meat', 3577, 2), ('rope', 3003, 30), ('shovel', 3457, 30),
    ('lightest magic missile rune', 17512, 3),
]
KEEPS_VALUE = {'gold coin', 'platinum coin', 'crystal coin', 'health potion', 'mana potion', 'meat'}
TOKEN_PRICE = 1
FOOD = re.compile(r'bread|cheese|ham|fish|cookie|apple|cherry|carrot|mushroom|grape|meat|melon|banana|roll')


def item_table(path):
    """id -> {name, attack, defense, armor}."""
    text = open(path, encoding='utf-8', errors='ignore').read()
    items = {}
    for m in re.finditer(r'<item\s+(?:id|fromid)="(\d+)"(?:\s+toid="(\d+)")?[^>]*?name="([^"]+)"[^>]*?(/>|>(.*?)</item>)', text, re.S):
        first, last, name, _, body = m.groups()
        stats = dict(re.findall(r'key="(attack|defense|armor)"\s+value="(\d+)"', body or ''))
        for item_id in range(int(first), int(last or first) + 1):
            items[item_id] = {'name': name.lower(), **{k: int(v) for k, v in stats.items()}}
    return items


def price_of(item):
    power = item.get('attack', 0) + item.get('defense', 0) + item.get('armor', 0) * 3
    if power:
        return min(300, max(5, power * 2))
    return 1 if FOOD.search(item['name']) else 3


def main(canary, spawns, out):
    names = set(re.findall(r'<monster name="([^"]+)"', open(spawns, encoding='utf-8').read()))
    items = item_table(os.path.join(canary, 'data', 'items', 'items.xml'))
    looted = {}
    for path in glob.glob(os.path.join(canary, 'data-canary', 'monster', '**', '*.lua'), recursive=True):
        text = open(path, encoding='utf-8', errors='ignore').read()
        name = re.search(r'Game\.createMonsterType\("([^"]+)"\)', text)
        block = re.search(r'monster\.loot\s*=\s*\{(.*?)\n\}', text, re.S)
        if not name or name.group(1) not in names or not block:
            continue
        for item_id in re.findall(r'\bid\s*=\s*(\d+)', block.group(1)):
            looted[int(item_id)] = True
        by_name = {v['name']: k for k, v in items.items()}
        for item_name in re.findall(r'name\s*=\s*"([^"]+)"', block.group(1)):
            if item_name.lower() in by_name:
                looted[by_name[item_name.lower()]] = True
    sold = {item_id for _, item_id, _ in SOLD}
    bought = [{'name': items[i]['name'], 'id': i, 'price': price_of(items[i])} for i in sorted(looted)
              if i in items and items[i]['name'] not in KEEPS_VALUE and i not in sold and 'potion' not in items[i]['name']]
    bought.append({'name': 'christmas token', 'id': 6526, 'price': TOKEN_PRICE})
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'Generated by tools/make_shop.py. Prices of this world, not of Tibia.', 'sold': [{'name': n, 'id': i, 'price': p} for n, i, p in SOLD], 'bought': bought}, f, ensure_ascii=False, indent=1)
    print({'sold': len(SOLD), 'bought': len(bought)})


if __name__ == '__main__':
    main(*sys.argv[1:4])
